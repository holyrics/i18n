<dl>
  <dt>Novidades</dt>
    <dd>• Integração com conteúdos do <b>Worshipwide</b> (requer assinatura). Faça download diretamente na janela de plano de fundo;</dd>
    <dd>• [Receptor] Novo tipo de receptor <b>"Holyrics Action"</b> (para uso em gatilhos) que permite executar uma ação nativa do programa, por exemplo, executar áudio, exibir imagem, etc.;</dd>
    <dd>• [Ações] Novo tipo de item nativo (para uso na barra de favoritos, lista de reprodução, etc.) que executa ações de contexto geral, como por exemplo, realizar ações no VLC Player, abrir janelas, alterar algumas configurações, como por exemplo a versão da Bíblia, etc.;</dd>
    <dd>• [Favoritos] Opção para pausar temporariamente a execução de gatilhos (dentro do novo item "Ações");</dd>
    <dd>• [JSLib] Botão de estado (boolean) para uso em regras e botões nos favoritos.</dd>
    <dd>&nbsp;</dd>

  <dt>Alterações</dt>
    <dd>• [Alerta] Exibir texto de alerta durante execução de vídeos no VLC Player;</dd>
    <dd>• [Rodapé de apresentação] Configuração para definir largura e altura máxima para o modo <b>Texto</b> e definir proporção fixa para modo <b>Imagem</b>;</dd>
    <dd>• [Janela da Bíblia] Atalho para abrir janela de pesquisa de trecho de versículos no livro atualmente selecionando <b>Ctrl+Shift+F</b>.</dd>
    <dd>&nbsp;</dd>

  <dt>Correções</dt>
    <dd>• Alterações feitas na janela de edição de receptores não são salvas;</dd>
    <dd>• Definir cor na formatação personalizada não salva a cor;</dd>
    <dd>• Parênteses duplicado na exibição da versão da Bíblia (no modo camada);</dd>
    <dd>• Possível congelamento temporário da interface quando a <i>function actions()</i> de um módulo demora pra ser executada;</dd>
    <dd>• Possível crash ao listar webcams;</dd>
    <dd>• Outras correções e melhorias de performance...</dd>
</dl>